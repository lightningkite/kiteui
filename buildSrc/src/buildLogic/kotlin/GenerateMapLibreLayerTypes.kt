import com.lightningkite.kiteui.camelCase
import com.lightningkite.kiteui.pascalCase
import kotlinx.serialization.*
import kotlinx.serialization.json.*
import java.io.File

/** Generates typed MapLibre layer classes from the MapLibre style spec (`v8.json`). */
fun generateMapLibreLayerTypes(
    specFile: File,
    cocoaConventionsFile: File,
    packageName: String,
    webVersion: String,
    androidVersion: String,
    iosVersion: String,
    outputDir: File,
) {
    val json = Json { ignoreUnknownKeys = true }

    val spec = json.parseToJsonElement(specFile.readText()).jsonObject
    val layerSpec = json.decodeFromJsonElement<LayerSpec>(spec.getValue("layer"))
    val context = PropertyContext(
        cocoaConventions = json.decodeFromString(cocoaConventionsFile.readText()),
        versionsInUse = mapOf(
            "js" to webVersion, "android" to androidVersion, "ios" to iosVersion
        ).mapValues { (key, version) -> parseVersion(version) ?: error("Invalid $key version") },
    )

    // Every paint and layout property of every layer type, except those no platform supports.
    val propertiesByLayer = layerSpec.type.values.keys.associateWith { layerType ->
        val groups = listOf("paint", "layout").associateWith { group ->
            json.decodeFromJsonElement<Map<String, PropertySpec>>(
                spec["${group}_$layerType"] ?: error("The style spec has no '${group}_$layerType'")
            )
        }
        val layerPropertyNames = groups.values.flatMap { it.keys }.toSet()
        groups.flatMap { (group, specs) ->
            specs.map { (name, propertySpec) ->
                StyleProperty(layerType, group, name, propertySpec, layerPropertyNames, context)
            }
        }.filter { it.unsupportedOn.size < 3 }
    }


    /**
     * Groups enum properties by name, minus their layer and `icon-` or `text-` prefixes, then by
     * values. Each group of properties with the same values shares one enum:
     * - Used by multiple layer types: top-level, named after the group (`TranslateAnchor`).
     * - Used by one layer type: nested in that layer's class, named after the group if multiple
     *   properties share it (`SymbolLayer.Anchor`), or else the property without its layer
     *   prefix (`CircleLayer.PitchAlignment`, `SymbolLayer.IconTextFit`).
     *
     * Returns the enum of each enum property, by property name.
     */
    val enums = propertiesByLayer.values.flatten().let { properties ->
        val result = HashMap<String, StyleEnum>()
        val enumProperties = properties.filter { it.enumValues != null }
        for ((enumKey, byKey) in enumProperties.groupBy { SHARED_ENUMS[it.name] ?: it.enumKey }) {
            for (group in byKey.groupBy { it.enumValues!!.keys }.values) {
                val owner = group.map { it.layerType }.distinct().singleOrNull()
                val name = (if (group.size > 1) enumKey else group.single().shortName).pascalCase()
                val enum = StyleEnum(name, owner, group.first().enumValues!!)
                for (property in group) result[property.name] = enum
            }
        }
        for ((reference, clashing) in result.values.distinct().groupBy { it.reference }) {
            check(clashing.size == 1) { "Generated enums clash on the name $reference" }
        }
        result
    }

    val enumsByOwner = enums.values.distinct().sortedBy { it.name }.groupBy { it.ownerLayerType }

    outputDir.deleteRecursively()
    val packageDir = outputDir.resolve(packageName.replace('.', '/')).apply { mkdirs() }
    fun writeKotlinFile(name: String, body: StringBuilder.() -> Unit) =
        packageDir.resolve("$name.kt").writeText(buildString {
            appendLine("// Generated by generateMapLibreLayerTypes from the MapLibre style spec. Do not edit.")
            appendLine("package $packageName")
            body()
        })

    writeKotlinFile("StyleEnums") { enumsByOwner[null]?.forEach { appendEnum(it, "") } }

    propertiesByLayer.forEach { (layerType, properties) ->
        writeKotlinFile(layerClassName(layerType)) {
            appendLine()
            appendLine("import com.lightningkite.kiteui.map.MapView")
            appendLine("import com.lightningkite.kiteui.models.Color")
            appendLine("import com.lightningkite.kiteui.models.ImageSource")
            appendLine("import kotlin.uuid.Uuid")
            appendLine()
            val typeDoc = layerSpec.type.values.getValue(layerType)?.doc ?: "A $layerType layer."
            appendKdoc("$typeDoc\n\nSee https://maplibre.org/maplibre-style-spec/layers/#$layerType", "")
            appendLine("class ${layerClassName(layerType)}<P> internal constructor(mapView: MapView, id: Uuid, source: Uuid) : Layer<P>(mapView, id, source, \"$layerType\") {")

            if (layerType in FILTERABLE_LAYER_TYPES) {
                val filterDoc = layerSpec.filter?.doc ?: "Only features matching the filter are displayed."
                appendKdoc("$filterDoc\n\nSee https://maplibre.org/maplibre-style-spec/layers/#filter", "    ")
                appendLine("    var filter: Value<Boolean>? by filter()")
            }
            for (property in properties) {
                val native = property.unsupportedOn.isEmpty()
                appendLine()
                appendKdoc(property.kdoc(), "    ")
                append("    var ${property.shortName.camelCase()}: Value<${property.kotlinType(enums)}>? by ")
                appendLine("Property(PropertyGroup.${property.group.pascalCase()}, \"${property.name}\", \"${property.cocoaName}\", $native)")
            }
            for (enum in enumsByOwner[layerType].orEmpty()) appendEnum(enum, "    ")
            appendLine("}")
        }
    }
}

private class StyleEnum(val name: String, val ownerLayerType: String?, val values: Map<String, String?>) {
    /** How generated code refers to this enum. */
    val reference = if (ownerLayerType == null) name else "${layerClassName(ownerLayerType)}.$name"
}

/** What [StyleProperty] needs from outside the style spec. */
private class PropertyContext(
    /** Per `paint_*`/`layout_*` group, each renamed property's iOS name or `{"name": ...}`. */
    val cocoaConventions: Map<String, Map<String, JsonElement>>,
    /** The MapLibre version in use per `sdk-support` platform key. */
    val versionsInUse: Map<String, KotlinVersion>,
)

private class StyleProperty(
    val layerType: String,
    val group: String,
    val name: String,
    val spec: PropertySpec,
    /** The names of all properties of [layerType], to avoid shortening one into another. */
    layerPropertyNames: Set<String>,
    context: PropertyContext,
) {
    /**
     * The name without the layer prefix, unless that is another property's name (`raster-resampling`
     * vs. `resampling`). `symbol` properties keep their `icon-` and `text-` prefixes.
     */
    val shortName = name.removePrefix("$layerType-").takeUnless { it != name && it in layerPropertyNames } ?: name
    val enumKey = shortName.replace(Regex("^(icon|text)-"), "")

    /**
     * The key of the property on iOS's `MLN*StyleLayer`, which renames some properties. Renames to
     * `is-*` only change the getter's name, so they're dropped here like MapLibre Native does.
     */
    val cocoaName: String = when (val convention = context.cocoaConventions["${group}_$layerType"]?.get(name)) {
        null -> name
        is JsonObject -> convention.getValue("name").jsonPrimitive.content
        else -> convention.jsonPrimitive.content
    }.removePrefix("is-").camelCase()

    val enumValues: Map<String, String?>? = if (spec.type == "enum" || spec.type == "array" && spec.value == "enum") {
        (spec.values ?: error("Enum property $name has no values")).mapValues { it.value?.doc }
    } else null

    /**
     * Platforms without basic support in the versions in use: missing, an issue link rather than a
     * version, or a later version.
     */
    val unsupportedOn = listOf("js" to "Web", "android" to "Android", "ios" to "iOS").filter { (key, _) ->
        val since = spec.sdkSupport?.get("basic functionality")?.get(key)?.let(::parseVersion)
        since == null || since > context.versionsInUse.getValue(key)
    }.map { it.second }

    fun kotlinType(enums: Map<String, StyleEnum>): String = when (spec.type) {
        "number" -> "Number"
        "boolean" -> "Boolean"
        "string" -> "String"
        "color" -> "Color"
        "enum" -> enums.getValue(name).reference
        "formatted" -> "String"
        "resolvedImage" -> "ImageSource"
        "padding" -> "Padding"
        "numberArray" -> "List<Number>"
        "colorArray" -> "List<Color>"
        "variableAnchorOffsetCollection" -> "AnchorOffsets"
        "array" -> when (spec.value) {
            "number" -> when (spec.length) {
                2 -> "Point"
                4 -> "Padding"
                null -> "List<Number>"
                else -> error("Unsupported number array length for $name")
            }

            "string" -> "List<String>"
            "enum" -> "List<${enums.getValue(name).reference}>"
            else -> error("Unsupported array item type '${spec.value}' for $name")
        }

        else -> error("Unsupported style spec type '${spec.type}' for $name")
    }

    fun kdoc(): String = buildList {
        add("Style spec: [`$name`](https://maplibre.org/maplibre-style-spec/layers/#$name)")
        spec.doc?.let { add(it) }
        spec.requires?.let { add("Requires: ${formatJson(JsonArray(it))}") }
        spec.default?.let { add("Default: `${formatJson(it)}`") }
        spec.units?.let { add("Units: $it") }
        spec.minimum?.let { add("Minimum: ${it.content}") }
        spec.maximum?.let { add("Maximum: ${it.content}") }
        when (spec.propertyType) {
            "data-constant" -> add("Can't depend on feature data")
            "color-ramp" -> add("Evaluated per point along the line with `lineProgress()`")
        }
        if (unsupportedOn.isNotEmpty()) {
            add("**Not supported on ${unsupportedOn.joinToString()}**")
            add("Setting this re-adds the layer, since it can't be set on the live layer on every platform.")
        }
    }.joinToString("\n\n")
}

@Serializable
private class LayerSpec(val type: EnumSpec, val filter: Documented? = null)

@Serializable
private class EnumSpec(val values: Map<String, Documented?>)

@Serializable
private class Documented(val doc: String? = null)

@Serializable
private class PropertySpec(
    val type: String,
    val value: String? = null,
    val values: Map<String, Documented?>? = null,
    val length: Int? = null,
    val doc: String? = null,
    val requires: List<JsonElement>? = null,
    val default: JsonElement? = null,
    val units: String? = null,
    val minimum: JsonPrimitive? = null,
    val maximum: JsonPrimitive? = null,
    @SerialName("property-type") val propertyType: String? = null,
    @SerialName("sdk-support") val sdkSupport: Map<String, Map<String, String>>? = null,
)

/** Enum properties that should reuse another property's enum key, despite different names. */
private val SHARED_ENUMS = mapOf("text-variable-anchor" to "anchor")

/** The property whose enum `AnchorOffset.anchor` uses. */
private const val ANCHOR_OFFSET_ANCHOR_PROPERTY = "text-anchor"

/** The layer types drawing features from a source, which can be filtered. */
private val FILTERABLE_LAYER_TYPES = setOf("circle", "fill", "fill-extrusion", "heatmap", "line", "symbol")

private fun layerClassName(layerType: String) = layerType.pascalCase() + "Layer"

/** Parses a version like `6.2.0`, or returns null if it isn't one (e.g. an issue link). */
private fun parseVersion(version: String): KotlinVersion? {
    val parts = version.split('.').map { it.toIntOrNull() ?: return null } + 0 + 0
    return KotlinVersion(parts[0], parts[1], parts[2])
}

private fun formatJson(value: JsonElement): String = when (value) {
    is JsonArray -> value.joinToString(", ", "[", "]") { formatJson(it) }
    is JsonObject -> value.entries.joinToString(", ", "{", "}") { (key, item) -> "\"$key\": ${formatJson(item)}" }
    is JsonPrimitive -> value.toString()
}

private fun StringBuilder.appendKdoc(text: String, indent: String) {
    appendLine("$indent/**")
    for (line in text.replace("*/", "*&#47;").trim().lines().map { it.trimEnd() }) {
        appendLine(if (line.isEmpty()) "$indent *" else "$indent * $line")
    }
    appendLine("$indent */")
}

/** Appends a blank line, then the enum. */
private fun StringBuilder.appendEnum(enum: StyleEnum, indent: String) {
    appendLine()
    appendLine("${indent}enum class ${enum.name}(override val value: String) : Layer.StyleEnum<${enum.name}> {")
    for ((value, doc) in enum.values) {
        doc?.let { appendKdoc(it, "$indent    ") }
        appendLine("$indent    ${value.pascalCase()}(\"$value\"),")
    }
    appendLine("$indent}")
}
